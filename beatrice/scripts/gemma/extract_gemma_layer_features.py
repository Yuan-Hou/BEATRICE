"""Per-layer answer-token hidden extraction for the gemma-4-E4B layer sweep.

Record protocol (v3, user 2026-07-16): the answer tokens are the stored label-time
answer (generations_final runs[run_key].extracted_answer) teacher-forced after the
turn prompt — no fresh generation, so every scoped row is kept and the hiddens
match the answers the labels were judged on (also what the SAPLMA/SEP baselines
will reuse these features for).

Mirrors the Qwen sweep protocol (scripts/extract_layer_features.py +
layer_sweep_curves.py): training-format prompt (QUESTION_ONLY / LEGACY_MUSIQUE),
greedy short answer generated by the model itself, then one full forward with
output_hidden_states; store per-layer last-answer-token and mean-answer-token
hiddens. Differences forced by the base swap:
  - prompt wrapped in the Gemma turn format (same as label construction;
    tokenizer adds BOS), <end_of_turn> serves as EOS;
  - 42 blocks + embeddings = 43 layers, d=2560;
  - examples/labels come from the finalized Gemma scope
    (configs/sampling/gemma4_scope_ids.json + data/gemma4/{sources_final,labels/final}).

Labels match the Qwen baseline configs: noctx -> without_context correct,
withctx -> with_context correct (1.0 = correct).

Output (npz + index.jsonl per shard, loadable by faithful.load_layer_features):
  data/gemma4/layer_features/<setting>/<group>__shard{i}of{n}.npz
      hidden_last [N, 43, 2560] fp16, hidden_mean [N, 43, 2560] fp16
  ...__shard{i}of{n}.index.jsonl   {example_id, dataset, label, answer_len}
  ...__shard{i}of{n}.done          success marker (written last)

Usage:
  CUDA_VISIBLE_DEVICES=2 python scripts/gemma/extract_gemma_layer_features.py \
      --setting noctx --group train --shard 0/6
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch
from tqdm import tqdm

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from ragprobe.prompts.qa import LEGACY_MUSIQUE_FEATURE_PROMPT, QUESTION_ONLY_FEATURE_PROMPT  # noqa: E402

MODEL = "google/gemma-4-E4B-it"  # canonical chat template applies (no hand-rolled turns)
OUT_BASE = ROOT / "data" / "gemma4" / "layer_features"
IN_DOMAIN = ("hotpotqa_supporting_only", "musique", "twowiki_supporting_only", "popqa")
MAX_NEW_TOKENS = 32
MAX_INPUT_TOKENS = 6144
# gemma full-attention layers; the sliding-window layers are the protocol analog of
# qwen's linear-attention layers (excluded there too) for the LLM-Check attn score
FULL_ATTN_LAYERS = (5, 11, 17, 23, 29, 35, 41)


def gram_logdet(h: torch.Tensor) -> float:
    """LLM-Check hidden score: log|det| of the centered token Gram matrix / n."""
    n = h.shape[0]
    if n < 2:
        return 0.0
    h = h.float()
    h = h - h.mean(dim=0, keepdim=True)
    g = h @ h.t()
    g = g + 1e-3 * torch.eye(n, device=g.device, dtype=g.dtype)
    sign, logabsdet = torch.linalg.slogdet(g)
    return float(logabsdet.item() / n)


def attn_logdet_score(attn_qk: torch.Tensor) -> float:
    """Mean over heads of log|det| of the answer-token attention sub-matrix."""
    heads, n, _ = attn_qk.shape
    if n < 2:
        return 0.0
    a = attn_qk.float()
    a = a + 1e-3 * torch.eye(n, device=a.device, dtype=a.dtype).unsqueeze(0)
    sign, logabsdet = torch.linalg.slogdet(a)
    return float((logabsdet / n).mean().item())


def install_attn_taps(model, captured: dict):
    """Force the full-attention layers to return eager attention weights into
    `captured[layer_idx]` without materializing all-layer attentions."""
    layers = model.model.language_model.layers  # multimodal wrapper: decoder lives here
    for li in FULL_ATTN_LAYERS:
        mod = layers[li].self_attn
        orig = mod.forward

        def fwd(*a, _orig=orig, _li=li, **k):
            k["output_attentions"] = True
            out = _orig(*a, **k)
            if isinstance(out, tuple) and len(out) > 1 and out[1] is not None:
                captured[_li] = out[1]
            return out

        mod.forward = fwd


def load_group_ids(group: str) -> list[str]:
    sc = json.load((ROOT / "configs/sampling/gemma4_scope_ids.json").open())
    scope = sc["ids"]
    if group == "train":
        return scope["train"]
    if group == "validation":
        return scope["validation"]
    if group == "test_id":
        return [i for i in scope["test"] if not i.startswith("popqa-")]
    if group == "popqa_ood":
        return [i for i in scope["test"] if i.startswith("popqa-")]
    if group in ("nq", "triviaqa"):
        return sc["extra_ids"][group]
    if group == "train_rewritten":
        # rewritten-context aug rows reuse the base example id; the training
        # partition keeps those in scope train — mirror that here
        rew = {json.loads(l)["id"] for l in
               (ROOT / "data/gemma4/labels/final/rewritten_context_labels.jsonl").open()}
        return [i for i in scope["train"] if i in rew]
    raise ValueError(group)


# datasets whose sources/labels/answers to load per group
def group_datasets(group: str) -> tuple[str, ...]:
    if group in ("nq", "triviaqa"):
        return (group,)
    if group == "train_rewritten":
        return ("rewritten_context",)
    return IN_DOMAIN


def format_context_legacy(example: dict) -> str:
    rows = []
    for ctx in example.get("contexts") or []:
        text = ctx if isinstance(ctx, str) else (ctx.get("text") or ctx.get("paragraph_text") or "")
        text = str(text).strip()
        if text:
            rows.append("- " + text)
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--setting", required=True, choices=("noctx", "withctx"))
    ap.add_argument("--group", required=True,
                    choices=("train", "validation", "test_id", "popqa_ood",
                             "nq", "triviaqa", "train_rewritten"))
    ap.add_argument("--shard", default="0/1")
    args = ap.parse_args()
    si, sn = (int(x) for x in args.shard.split("/"))

    out_dir = OUT_BASE / args.setting
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{args.group}__shard{si}of{sn}"
    npz_path = out_dir / f"{stem}.npz"
    done_path = out_dir / f"{stem}.done"
    if done_path.exists():
        print(f"already done: {done_path}")
        return

    ids = load_group_ids(args.group)[si::sn]
    examples, labels, answers = {}, {}, {}
    run_key = "without_context" if args.setting == "noctx" else "with_context"
    for name in group_datasets(args.group):
        for line in (ROOT / f"data/gemma4/sources_final/{name}.jsonl").open():
            ex = json.loads(line)
            examples[ex["id"]] = ex
        for line in (ROOT / f"data/gemma4/labels/final/{name}_labels.jsonl").open():
            lab = json.loads(line)
            labels[lab["id"]] = 1.0 if lab["runs"][run_key]["is_correct"] else 0.0
        # feature-answer protocol (user 2026-07-16): training-format greedy answers
        # pre-generated by vLLM (gen_trainfmt_answers_vllm.py) — no HF generation
        for line in (ROOT / f"data/gemma4/trainfmt_answers/{name}.jsonl").open():
            rec = json.loads(line)
            answers[rec["id"]] = str((rec.get("answers") or {}).get(run_key) or "").strip()
    missing = [i for i in ids if i not in examples or i not in labels or i not in answers]
    if missing:
        raise RuntimeError(f"{len(missing)} scope ids missing example/label/answer, e.g. {missing[:3]}")

    from transformers import AutoTokenizer, AutoModelForCausalLM
    tok = AutoTokenizer.from_pretrained(MODEL)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL, dtype=torch.bfloat16, attn_implementation="eager").cuda().eval()
    captured_attn: dict = {}
    install_attn_taps(model, captured_attn)

    h_last, h_mean, h_logdet, a_logdet = [], [], [], []
    ppl, ment, maxent, index = [], [], [], []
    n_skip = 0
    for eid in tqdm(ids, desc=stem):
        ex = examples[eid]
        question = str(ex.get("question") or "").strip()
        if args.setting == "noctx":
            base_prompt = QUESTION_ONLY_FEATURE_PROMPT.substitute(question=question)
        else:
            context = format_context_legacy(ex).strip()
            if not context:
                n_skip += 1
                continue
            base_prompt = LEGACY_MUSIQUE_FEATURE_PROMPT.substitute(context=context, question=question)
        ans_text = answers.get(eid, "")
        if not ans_text:
            n_skip += 1
            continue
        enc = tok.apply_chat_template(
            [{"role": "user", "content": base_prompt}],
            add_generation_prompt=True, tokenize=True, return_dict=True,
            return_tensors="pt", enable_thinking=False,
            truncation=True, max_length=MAX_INPUT_TOKENS,
        ).to("cuda")
        p_len = enc["input_ids"].shape[1]
        clean_ids = torch.tensor(tok(ans_text, add_special_tokens=False)["input_ids"],
                                 dtype=torch.long)[:MAX_NEW_TOKENS]
        if clean_ids.numel() == 0:
            n_skip += 1
            continue
        a_len = int(clean_ids.numel())
        seq = torch.cat([enc["input_ids"][0], clean_ids.to("cuda")]).unsqueeze(0)
        captured_attn.clear()
        with torch.no_grad():
            out = model(input_ids=seq, output_hidden_states=True)
        hs = torch.stack(out.hidden_states, dim=0)[:, 0]  # [43, T, 2560]
        span = hs[:, p_len:p_len + a_len]
        h_last.append(span[:, -1].to(torch.float16).cpu().numpy())
        h_mean.append(span.float().mean(dim=1).to(torch.float16).cpu().numpy())
        h_logdet.append(np.array([gram_logdet(layer_h) for layer_h in span], dtype=np.float32))

        # logit scalars over answer tokens (predict pos t from logits at t-1)
        a_pos = torch.arange(p_len, p_len + a_len, device=seq.device)
        logits = out.logits[0, a_pos - 1].float()
        probs = torch.softmax(logits, -1)
        p = probs.gather(1, seq[0, a_pos].unsqueeze(1)).squeeze(1).clamp_min(1e-10)
        ent = -(probs * (probs + 1e-10).log()).sum(-1)
        ppl.append(float((-p.log()).mean().exp().item()))
        ment.append(float(ent.mean().item()))
        maxent.append(float(ent.max().item()))

        a_scores = []
        for li in FULL_ATTN_LAYERS:
            attn = captured_attn.get(li)
            if attn is None:
                a_scores = None
                break
            sub = attn[0][:, a_pos][:, :, a_pos]  # [heads, n_ans, n_ans]
            a_scores.append(attn_logdet_score(sub))
        if a_scores is None:
            raise RuntimeError("attention tap returned nothing; check transformers version")
        a_logdet.append(np.array(a_scores, dtype=np.float32))

        index.append({"example_id": eid, "dataset": ex.get("dataset"),
                      "label": labels[eid], "answer_len": a_len})

    tmp = npz_path.with_suffix(".npz.tmp.npz")
    np.savez_compressed(
        tmp, hidden_last=np.stack(h_last), hidden_mean=np.stack(h_mean),
        hid_logdet=np.stack(h_logdet), attn_logdet=np.stack(a_logdet),
        perplexity=np.array(ppl, dtype=np.float32),
        mean_entropy=np.array(ment, dtype=np.float32),
        max_entropy=np.array(maxent, dtype=np.float32))
    tmp.rename(npz_path)
    with (out_dir / f"{stem}.index.jsonl").open("w") as f:
        for r in index:
            f.write(json.dumps(r) + "\n")
    done_path.write_text(f"n={len(index)} skipped={n_skip}\n")
    print(f"DONE {stem}: n={len(index)} skipped={n_skip}")


if __name__ == "__main__":
    main()
